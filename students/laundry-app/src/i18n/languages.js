export const getTranslation = (lang, key, params = {}) => {
  let text = translations[lang]?.[key] || translations['en'][key] || key;
  Object.keys(params).forEach(param => {
    text = text.replace(new RegExp(`{${param}}`, 'g'), params[param]);
  });
  return text;
};
